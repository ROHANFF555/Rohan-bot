"""Bangla Synonym Library — ইন্টেন্ট ম্যাচিংয়ের জন্য সমার্থক-শব্দ গ্রুপ।

`brain_patterns`-এর `intent` টাইপ প্যাটার্ন ম্যাচ করার সময় (main.py →
PatternEngine._score_pattern) ইউজারের মেসেজের টোকেনগুলো এই গ্রুপ দিয়ে
প্রসারিত করা হয়, যাতে একই অর্থের আলাদা শব্দেও (যেমন "যোগ" বনাম "মোট বের করো")
একই ইন্টেন্ট ধরা যায়।

প্রতিটা গ্রুপ = একই অর্থের শব্দের সেট। কোনো টোকেন যেকোনো গ্রুপে থাকলে সেই
গ্রুপের সব শব্দ টোকেন-সেটে যোগ হয় (`expand_with_synonyms`)।

নতুন গ্রুপ যোগ করার নিয়ম:
  - একই অর্থের শব্দগুলো একটাই গ্রুপে রাখো (গ্রুপ আলাদা হলে cross-match হয় না)।
  - শব্দ ছোট রাখার চেষ্টা করো — বটের মেসেজ টোকেনাইজ হয় শব্দ-শব্দে।
"""

from __future__ import annotations

# প্রতিটা সেট = একই অর্থের শব্দের গ্রুপ (Bangla + ইংরেজি মিশিয়ে)
SYNONYM_GROUPS: list[set[str]] = [
    {"যোগ", "যোগ করো", "মোট", "মোট বের করো", "যুক্ত", "add", "addition", "সাম"},
    {"বিয়োগ", "বাদ দাও", "বিয়োগ করো", "minus", "subtract"},
    {"গুণ", "গুণ করো", "গুনা", "multiply"},
    {"ভাগ", "ভাগ করো", "divide"},
    {"প্রিন্ট", "দেখাও", "লেখো", "print", "show", "display", "আউটপুট"},
    {"সংরক্ষণ", "সেভ", "রাখো", "store", "save"},
    {"মুছো", "ডিলিট", "delete", "remove", "হটাও"},
    {"খোঁজো", "সার্চ", "search", "find", "বের করো"},
    {"তালিকা", "লিস্ট", "list", "দেখাও সব"},
    {"সাহায্য", "হেল্প", "help", "সহযোগিতা", "সহায়তা"},
    {"অনুবাদ", "translate", "ভাষান্তর", "ট্রান্সলেট"},
    {"সারসংক্ষেপ", "সারাংশ", "summarize", "সামারি", "সংক্ষেপ"},
]


def expand_with_synonyms(tokens: set) -> set:
    """একটা টোকেন-সেট দিলে সমার্থক শব্দসহ বড় সেট ফেরায়।

    - ইনপুটের সব টোকেন অপরিবর্তিত থাকে।
    - কোনো টোকেন কোনো গ্রুপে থাকলে সেই গ্রুপের পুরো সেট যোগ হয়।
    - খালি সেট দিলে খালি সেটই ফেরত আসে।
    """
    expanded = set(tokens)
    for group in SYNONYM_GROUPS:
        if expanded & group:  # যদি কোনো টোকেন এই গ্রুপে থাকে
            expanded |= group  # পুরো গ্রুপ যোগ করো
    return expanded
